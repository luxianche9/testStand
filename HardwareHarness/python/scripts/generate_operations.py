"""Write the TypeScript operation metadata and ``openapi.json`` from the Python registry.

``OPERATIONS`` gives the HTTP clients what they need to turn a positional call into the named
JSON body of ``POST /api/ops/{name}``: the wire parameter names in order, which of them are
bytes (base64 on the wire) and whether the result is bytes. ``DESKTOP_OPERATIONS`` are the
renderer's; ``HOST_OPERATIONS`` (``desktop.*``) only the main process may call.
"""

from __future__ import annotations

import json
from pathlib import Path

from hardwareharness_backend.host.runtime import SERVICE_OPERATIONS, openapi

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "packages/contracts/src/operations.generated.ts"
OPENAPI = ROOT / "packages/contracts/openapi.json"
HOST_NAMESPACE = "desktop"


def _names(names: list[str]) -> str:
    return "".join(f'  "{name}",\n' for name in names)


def render() -> str:
    metadata = []
    for name, definition in SERVICE_OPERATIONS.items():
        entry = {
            "params": [wire for wire, _ in definition.parameters],
            "bytes": list(definition.bytes_fields),
            "returnsBytes": definition.returns_bytes,
            "risk": definition.spec.risk,
            "capability": definition.spec.capability,
        }
        metadata.append(f'  "{name}": {json.dumps(entry, separators=(", ", ": "))},\n')
    renderer = [
        name for name, item in SERVICE_OPERATIONS.items() if item.namespace != HOST_NAMESPACE
    ]
    host = [name for name, item in SERVICE_OPERATIONS.items() if item.namespace == HOST_NAMESPACE]
    return (
        "// Generated by python/scripts/generate_operations.py from the Python @operation\n"
        "// registry. Do not edit; rerun the script after adding or renaming an operation.\n"
        "export interface OperationMetadata {\n"
        "  readonly params: readonly string[];\n"
        "  readonly bytes: readonly string[];\n"
        "  readonly returnsBytes: boolean;\n"
        '  readonly risk: "read" | "write" | "actuate" | "destructive";\n'
        "  readonly capability: string;\n"
        "}\n\n"
        f"export const OPERATIONS = {{\n{''.join(metadata)}}} as const satisfies "
        "Record<string, OperationMetadata>;\n\n"
        "export type OperationName = keyof typeof OPERATIONS;\n\n"
        f"export const DESKTOP_OPERATIONS = [\n{_names(renderer)}] as const;\n\n"
        "export type DesktopOperation = (typeof DESKTOP_OPERATIONS)[number];\n\n"
        f"export const HOST_OPERATIONS = [\n{_names(host)}] as const;\n\n"
        "export type HostOperation = (typeof HOST_OPERATIONS)[number];\n"
    )


def render_openapi() -> str:
    return json.dumps(openapi(), indent=2, ensure_ascii=False, sort_keys=False) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    OPENAPI.write_text(render_openapi(), encoding="utf-8", newline="\n")
