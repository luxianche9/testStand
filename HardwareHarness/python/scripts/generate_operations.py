"""Write ``openapi.json`` and the TypeScript operation list from the Python registry.

``packages/contracts/openapi.json`` describes every ``POST /api/ops/{name}`` with its named
JSON request; ``packages/contracts/scripts/generate-openapi-types.mjs`` (openapi-typescript)
turns it into the request types of ``openapi.generated.ts``, which this script runs last.
``operations.generated.ts`` lists the operation names, so the renderer can build one function
per operation, and the operations whose result is bytes (base64 on the wire). The API serves
neither file: they exist at build time only.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

from hardwareharness_backend import __version__
from hardwareharness_backend.contracts.openapi import openapi_document
from hardwareharness_backend.host.runtime import SERVICE_OPERATIONS

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "packages/contracts/src/operations.generated.ts"
OPENAPI = ROOT / "packages/contracts/openapi.json"
TYPES_SCRIPT = ROOT / "packages/contracts/scripts/generate-openapi-types.mjs"


def _names(names: list[str]) -> str:
    return "".join(f'  "{name}",\n' for name in names)


def render() -> str:
    names = list(SERVICE_OPERATIONS)
    returns_bytes = [name for name, item in SERVICE_OPERATIONS.items() if item.returns_bytes]
    return (
        "// Generated by python/scripts/generate_operations.py from the Python @operation\n"
        "// registry. Do not edit; rerun the script after adding or renaming an operation.\n"
        f"export const OPERATION_NAMES = [\n{_names(names)}] as const;\n\n"
        "export type OperationName = (typeof OPERATION_NAMES)[number];\n\n"
        "/** Operations whose result is bytes, sent as base64. */\n"
        "export const BYTES_RESULT_OPERATIONS: readonly OperationName[] = [\n"
        f"{_names(returns_bytes)}];\n"
    )


def render_openapi() -> str:
    document = openapi_document(SERVICE_OPERATIONS, __version__)
    return json.dumps(document, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    OPENAPI.write_text(render_openapi(), encoding="utf-8", newline="\n")
    subprocess.run(["node", str(TYPES_SCRIPT)], cwd=ROOT, check=True)
